#!/usr/bin/env python3
"""gen_bench_guys_text.py — generate dos_port/assets/bench_guys_text.inc (Tier 1 data).

Generates:
1. SaffronCityPokecenterBenchGuyText1 and SaffronCityPokecenterBenchGuyText2
   (flattened text streams from pret engine/events/hidden_events/bench_guys.asm
   referencing data/text/text_2.asm).
2. BenchGuyTextPointers table (from pret data/events/bench_guys.asm).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "bench_guys_text.inc"

SRC_FILES = ["engine/events/hidden_events/bench_guys.asm"]
WANT = {"SaffronCityPokecenterBenchGuyText1", "SaffronCityPokecenterBenchGuyText2"}


def parse_bench_guy_table():
    """Parse data/events/bench_guys.asm into a list of (map_const, facing_const, text_predef_label)."""
    table_path = ROOT / "data" / "events" / "bench_guys.asm"
    entries = []
    for line in table_path.read_text(encoding="utf-8").splitlines():
        line = line.split(";", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^bench_guy_text\s+(\w+)\s*,\s*(\w+)\s*,\s*(\w+)", line)
        if m:
            entries.append((m.group(1), m.group(2), m.group(3)))
    return entries


def main() -> int:
    charmap = gbt.load_charmap()
    memmap = gbt.load_memmap()
    far_db = gbt.collect_far(charmap, memmap)

    gbt.BATTLE_SRC = SRC_FILES
    wrappers = gbt.collect_wrappers(charmap, memmap, far_db)

    missing = WANT - set(wrappers)
    if missing:
        raise SystemExit(
            f"gen_bench_guys_text: expected labels missing from scan: {sorted(missing)}")

    labels = sorted(WANT)
    table_entries = parse_bench_guy_table()
    if not table_entries:
        raise SystemExit("gen_bench_guys_text: no entries found in data/events/bench_guys.asm")

    out = [
        "; bench_guys_text.inc — generated by tools/generators/gen_bench_guys_text.py. DO NOT EDIT BY HAND.",
        "; Bench guys text streams and BenchGuyTextPointers table.",
        "; Source: engine/events/hidden_events/bench_guys.asm, data/events/bench_guys.asm.",
        "",
        "section .data",
        "align 4",
        "",
        "global BenchGuyTextPointers",
        "BenchGuyTextPointers:",
    ]

    for map_name, facing, text_label in table_entries:
        out.append(f"    db {map_name:<30}, {facing:<20}, {text_label}_id")
    out.append("    db 0xFF")
    out.append("")

    for label in labels:
        b = wrappers[label]
        out.append(f"global {label}")
        out.append(f"{label}:")
        for i in range(0, len(b), 16):
            out.append("    db " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
        out.append(f"global {label}_ref")
        out.append(f"{label}_ref: dd {label}, {len(b)}   ; flat ptr + byte count")
        out.append(f"{label}_len equ {len(b)}")
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(labels)} label(s), table has {len(table_entries)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
