#!/usr/bin/env python3
"""Generate the Yellow-intro gfx includes (menu-intro B3.2b).

Converts the intro tile sheets (pret PNG -> GB 2bpp) and copies the intro
tilemaps into NASM includes, keeping the pret labels. Deterministic function of
the read-only pret gfx sources (gfx/intro/*), so rerunning is idempotent. The
png_to_2bpp core is shared with gen_title_gfx_inc.py and is verified byte-exact
against the committed gfx/intro/*.2bpp binaries.
"""
from pathlib import Path

from gen_globals import insert_globals
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_title_gfx_inc import png_to_2bpp

ROOT = Path(__file__).resolve().parent.parent.parent.parent
ASSETS = ROOT / "dos_port" / "assets"
GFX = ROOT / "gfx" / "intro"

HDR = "; {n} — generated by tools/generators/gen_intro_gfx_inc.py.  DO NOT EDIT BY HAND."


def _db_lines(data: bytes) -> list[str]:
    return ["    db " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]


def write_2bpp(dst: Path, label: str, data: bytes, comment: str,
               make_global: bool = False):
    n = len(data) // 16
    lines = [HDR.format(n=dst.name), f"; {comment}", "", f"{label}:"]
    lines += _db_lines(data)
    lines += [f"{label}End:",
              f"{label.upper()}_SIZE equ {label}End - {label}",
              f"{label.upper()}_TILES equ {n}", ""]
    if make_global:
        insert_globals(lines, [label], anchor=None)
    dst.write_text("\n".join(lines) + "\n")
    print(f"  wrote {dst.name} ({len(data)} B, {n} tiles)")


def write_tilemaps(dst: Path, entries):
    """entries: list of (label, filename, width, height)."""
    lines = [HDR.format(n=dst.name),
             "; Yellow-intro tilemaps (scene 10, flying Pikachu). Row-major.", ""]
    for label, fname, w, h in entries:
        data = (GFX / fname).read_bytes()
        assert len(data) == w * h, f"{fname}: {len(data)} != {w}x{h}"
        lines += [f"; {w}x{h}", f"{label}:"]
        lines += _db_lines(data)
        lines += [f"{label}End:", ""]
    insert_globals(lines, [e[0] for e in entries], anchor=None)
    dst.write_text("\n".join(lines) + "\n")
    print(f"  wrote {dst.name} ({len(entries)} tilemaps)")


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    print("Generating Yellow-intro gfx include files...")
    write_2bpp(ASSETS / "yellow_intro_1_2bpp.inc", "YellowIntroGraphics1",
               png_to_2bpp(GFX / "yellow_intro_1.png"), "intro tile sheet 1 -> vChars2")
    write_2bpp(ASSETS / "yellow_intro_2_2bpp.inc", "YellowIntroGraphics2",
               png_to_2bpp(GFX / "yellow_intro_2.png"), "intro tile sheet 2 -> vChars0")
    write_2bpp(ASSETS / "yellow_intro_clouds_2bpp.inc", "YellowIntroCloudGFX",
               png_to_2bpp(GFX / "clouds.png"), "cloud tiles", make_global=True)
    write_tilemaps(ASSETS / "yellow_intro_tilemaps.inc", [
        ("Unkn_f9b6e", "unknown_f9b6e.tilemap", 20, 6),
        ("Unkn_f9be6", "unknown_f9be6.tilemap", 4, 3),
        ("Unkn_f9bf2", "unknown_f9bf2.tilemap", 2, 2),
    ])


if __name__ == "__main__":
    main()
