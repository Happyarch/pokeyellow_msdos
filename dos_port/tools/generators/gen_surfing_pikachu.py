def _db_lines(data: bytes) -> list[str]:
    return ["    db " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]


def _emit_file(out_path: Path, blobs: list, hdr: str):
    lines = [hdr, ""]
    labels = []

    for label, fname, expected_sz, comment, assert_fn in blobs:
        src = GFX / fname
        if not src.exists():
            sys.exit(f"Missing source file: {src}")
        data = src.read_bytes()
        sz = len(data)
        assert sz == expected_sz, f"{fname}: size {sz} != expected {expected_sz}"
        if assert_fn is not None:
            assert assert_fn(sz), f"{fname}: formula assertion failed on size {sz}"

        labels.append(label)
        labels.append(f"{label}End")

        lines.append(f"; {comment}")
        lines.append(f"{label}:")
        lines.extend(_db_lines(data))
        lines.append(f"{label}End:")
        lines.append(f"{label.upper()}_SIZE equ {label}End - {label}")
        lines.append("")

    insert_globals(lines, labels, anchor=None)
    out_path.write_text("\n".join(lines) + "\n")
    print(f"Generated {out_path.name} with {len(blobs)} blobs.")


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    _emit_file(ASSETS / "surfing_pikachu.inc", GFX_BLOBS,
               "; surfing_pikachu.inc — generated by tools/generators/gen_surfing_pikachu.py.  DO NOT EDIT BY HAND.")
