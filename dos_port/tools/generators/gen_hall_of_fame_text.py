#!/usr/bin/env python3
"""gen_hall_of_fame_text.py — generate dos_port/assets/hall_of_fame_text.inc (Tier 1).

engine/movie/hall_of_fame.asm carries six rendered strings, and every one of them
is Tier-1 data under the two-tier rule ("text strings are DATA — never hand-encode
charmap bytes"), so none of them may be written as `db 0x..` in the port's .asm:

  PlaceString literals   HallOfFameText, HoFMonInfoText, HoFPlayTimeText,
                         HoFMoneyText — pret writes these as `db "..."` with
                         `next` continuations, not as text_* command streams.
  text_far wrappers      DexSeenOwnedText, DexRatingText — flattened here the same
                         way gen_battle_text.py flattens its battle wrappers, so
                         PrintText gets a literal stream with no bank indirection.

Both halves read PRET'S OWN SOURCE rather than a re-typed copy of the words, which
is the point of the rule: the strings cannot drift from the disassembly.

Reuses gen_battle_text.py's charmap / memmap / text-macro parser. collect_wrappers
is driven off its module-level BATTLE_SRC list, so this generator rebinds that list
to the Hall of Fame source for the duration of the call — a documented reuse, not a
second parser.

DO NOT EDIT the output by hand — re-run this generator.
Run from repo root or dos_port/.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
SRC = "engine/movie/hall_of_fame.asm"
OUT = ROOT / "dos_port" / "assets" / "hall_of_fame_text.inc"

# The text_far wrappers collect_wrappers should emit from SRC.
WRAPPERS = ["DexSeenOwnedText", "DexRatingText"]

# The plain PlaceString literals, parsed out of SRC by _plain_strings below.
PLAIN = ["HallOfFameText", "HoFMonInfoText", "HoFPlayTimeText", "HoFMoneyText"]

CHAR_NEXT = 0x4E
CHAR_LINE = 0x4F
CONT_MACROS = {"next": CHAR_NEXT, "line": CHAR_LINE}


def _plain_strings(cm):
    """Parse `Label:` followed by db/next/line "..." runs out of pret's source.

    pret writes these as raw `db` string literals rather than text_ macros because
    they are PlaceString arguments, not TextCommandProcessor streams — so
    collect_wrappers does not see them and they need their own tiny parser. A
    `next`/`line` continuation contributes its control byte and then its text.
    """
    lines = (ROOT / SRC).read_text(encoding="utf-8").splitlines()
    out, label = {}, None
    for raw in lines:
        line = raw.split(";")[0].rstrip()
        if not line:
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):", line)
        if m:
            label = m.group(1) if m.group(1) in PLAIN else None
            continue
        if label is None:
            continue
        m = re.match(r'^\s+(db|next|line)\s+"(.*)"\s*$', line)
        if not m:
            label = None            # anything else ends the literal run
            continue
        data = out.setdefault(label, [])
        if m.group(1) in CONT_MACROS:
            data.append(CONT_MACROS[m.group(1)])
        data.extend(gbt.encode(m.group(2), cm))
    return out


def main() -> int:
    cm = gbt.load_charmap()
    mem = gbt.load_memmap()
    far = gbt.collect_far(cm, mem)

    saved = gbt.BATTLE_SRC
    try:
        gbt.BATTLE_SRC = [SRC]
        wrappers = gbt.collect_wrappers(cm, mem, far)
    finally:
        gbt.BATTLE_SRC = saved

    plain = _plain_strings(cm)

    out = [
        "; hall_of_fame_text.inc — generated by tools/generators/gen_hall_of_fame_text.py.",
        "; DO NOT EDIT BY HAND.",
        f"; Rendered strings of pret {SRC}: the four PlaceString literals and the two",
        "; text_far wrappers, with their far payloads flattened for the flat model.",
        "; %included by src/engine/movie/hall_of_fame.asm inside section .data so the",
        "; labels never land in an orphaned section (link.ld).",
        "",
    ]
    missing = []
    for label in PLAIN:
        if label not in plain:
            missing.append(label)
            continue
        out.append(gbt.fmt(label, plain[label]))
    for label in WRAPPERS:
        if label not in wrappers:
            missing.append(label)
            continue
        out.append(gbt.fmt(label, wrappers[label]))
    if missing:
        sys.stderr.write(f"gen_hall_of_fame_text: could not build {missing}\n")
        return 1
    out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(PLAIN)} strings + {len(WRAPPERS)} wrappers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
