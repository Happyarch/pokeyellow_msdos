#!/usr/bin/env python3
"""gen_default_names.py — generate dos_port/assets/default_names.inc.

The Oak-speech naming flow (menu-intro A4.4) needs the built-in default player /
rival names in two on-cartridge layouts, both Tier-1 charmap data:

  DefaultNamesPlayer / DefaultNamesRival
    The <NEXT>-separated menu string PlaceString renders in DisplayIntroNameTextBox
    (pret data/player/names.asm):  "NEW NAME" <NEXT> N1 <NEXT> N2 <NEXT> N3 "@"

  DefaultNamesPlayerList / DefaultNamesRivalList
    The '@'-terminated lookup list GetDefaultName scans (pret data/player/
    names_list.asm):  "NEW NAME@" N1 "@" N2 "@" N3 "@"

The names themselves come straight from pret constants/player_constants.asm
(NUM_PLAYER_NAMES=3): players YELLOW/ASH/JACK, rivals BLUE/GARY/JOHN. Encoded
through gb_text (the same charmap the port assembles against); the two control
bytes are inserted explicitly (<NEXT>=$4E, '@'=$50 — see constants/charmap.asm).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gb_text  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "default_names.inc"

NEXT = 0x4E   # charmap "<NEXT>" — PlaceString newline
TERM = 0x50   # charmap "@"      — string terminator

# pret constants/player_constants.asm (NUM_PLAYER_NAMES = 3).
PLAYER_NAMES = ["YELLOW", "ASH", "JACK"]
RIVAL_NAMES = ["BLUE", "GARY", "JOHN"]
NEW_NAME = "NEW NAME"


def menu_string(names: list) -> list:
    """<NEXT>-separated menu string: "NEW NAME" <NEXT> n1 <NEXT> n2 ... "@"."""
    b = gb_text.encode(NEW_NAME)
    for n in names:
        b.append(NEXT)
        b += gb_text.encode(n)
    b.append(TERM)
    return b


def lookup_list(names: list) -> list:
    """'@'-terminated lookup list: "NEW NAME@" n1 "@" n2 "@" ..."""
    b = gb_text.encode(NEW_NAME) + [TERM]
    for n in names:
        b += gb_text.encode(n) + [TERM]
    return b


def emit(out: list, label: str, data: list) -> None:
    out.append(f"global {label}")
    out.append(f"{label}:")
    for i in range(0, len(data), 16):
        out.append("    db " + ", ".join(f"0x{x:02X}" for x in data[i:i + 16]))


def main() -> int:
    out = [
        "; default_names.inc — generated by tools/generators/gen_default_names.py.",
        "; DO NOT EDIT BY HAND.",
        "; Built-in Oak-speech default player/rival names (pret data/player/",
        "; names.asm + names_list.asm), charmap-encoded. section .data (see link.ld).",
        "",
        "section .data",
        "",
    ]
    emit(out, "DefaultNamesPlayer", menu_string(PLAYER_NAMES))
    emit(out, "DefaultNamesRival", menu_string(RIVAL_NAMES))
    emit(out, "DefaultNamesPlayerList", lookup_list(PLAYER_NAMES))
    emit(out, "DefaultNamesRivalList", lookup_list(RIVAL_NAMES))
    # DisplayIntroNameTextBox's embedded box title (pret's local .namestring "NAME@").
    emit(out, "IntroNameString", gb_text.encode("NAME") + [TERM])
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} (4 labels: players {PLAYER_NAMES}, rivals {RIVAL_NAMES})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
