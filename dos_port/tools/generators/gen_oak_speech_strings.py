#!/usr/bin/env python3
"""gen_oak_speech_strings.py — generate dos_port/assets/oak_speech_strings.inc.

The Oak-speech intro (menu-intro A4) prints five text streams through the
ordinary text engine:

  OakSpeechText1      -> _OakSpeechText1        ("Hello there! ... the #MON PROF!")
  OakSpeechText2      -> _OakSpeechText2A + sound_cry_pikachu + _OakSpeechText2B
  IntroducePlayerText -> _IntroducePlayerText   ("First, what is your name?")
  IntroduceRivalText  -> _IntroduceRivalText
  OakSpeechText3      -> _OakSpeechText3

pret holds these as `text_far`-wrapped labels in
engine/movie/oak_speech/oak_speech.asm, bodies in data/text/text_3.asm. This
reuses gen_battle_text.py's charmap/memmap/macro parser (same text_far / sound
command handling — OakSpeechText2's sound_cry_pikachu is the ONE permitted silent
audio op in the intro, per the plan) and emits each label as a flattened,
self-terminating stream plus a `{ptr, len}` `<Label>_ref` pair (the PrintText
idiom — a cross-object label is loaded, not `mov`d).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "oak_speech_strings.inc"

OAK_SRC = ["engine/movie/oak_speech/oak_speech.asm"]

WANT = {
    "OakSpeechText1", "OakSpeechText2", "OakSpeechText3",
    "IntroducePlayerText", "IntroduceRivalText",
}


def existing_labels() -> set:
    """Labels other generated .inc files already define — never re-emit a global."""
    out = set()
    for inc in (ROOT / "dos_port" / "assets").glob("*.inc"):
        if inc.name == OUT.name:
            continue
        try:
            out |= set(re.findall(r"^global (\w+)$", inc.read_text(), re.M))
        except OSError:
            pass
    return out


def main() -> int:
    charmap = gbt.load_charmap()
    memmap = gbt.load_memmap()
    far_db = gbt.collect_far(charmap, memmap)

    gbt.BATTLE_SRC = OAK_SRC
    wrappers = gbt.collect_wrappers(charmap, memmap, far_db)

    missing = WANT - set(wrappers)
    if missing:
        raise SystemExit(f"gen_oak_speech_strings: expected labels missing from scan: {sorted(missing)}")

    skip = existing_labels()
    labels = sorted(k for k in WANT if k not in skip)
    if not labels:
        raise SystemExit("gen_oak_speech_strings: all wanted labels already defined elsewhere")

    out = [
        "; oak_speech_strings.inc — generated by tools/generators/gen_oak_speech_strings.py.",
        "; DO NOT EDIT BY HAND.",
        "; Oak-speech intro message streams (pret engine/movie/oak_speech/oak_speech.asm",
        f"; wrappers), text_far flattened. {len(labels)} labels. section .data (see link.ld).",
        "",
        "section .data",
        "",
    ]
    for label in labels:
        b = wrappers[label]
        out.append(f"global {label}")
        out.append(f"{label}:")
        for i in range(0, len(b), 16):
            out.append("    db " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
        out.append(f"global {label}_ref")
        out.append(f"{label}_ref: dd {label}, {len(b)}   ; flat ptr + byte count")
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(labels)} labels: {', '.join(labels)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
