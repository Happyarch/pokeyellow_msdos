#!/usr/bin/env python3
"""gen_unknown_list.py — generate dos_port/assets/unknown_list.inc (Tier 1 data).

pret data/pokemon/unknown_list.asm is a $FF-terminated species list, used only by
engine/pokemon/evos_moves.asm:Func_3b0a2 — which pret's own comment calls "a
unreferenced function". Transcribed rather than hand-copied so a 32-entry species
list cannot drift from the disassembly by a typo, and so re-running the generator
is what updates it.

Species names resolve through dos_port/assets/script_constants.inc, which is where
the port keeps the pret constants/pokemon_constants.asm values.

DO NOT EDIT the output by hand — re-run this generator.
Run from repo root or dos_port/.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "data" / "pokemon" / "unknown_list.asm"
CONSTS = ROOT / "dos_port" / "assets" / "script_constants.inc"
OUT = ROOT / "dos_port" / "assets" / "unknown_list.inc"

LABEL = "Pointer_3b0ee"


def load_consts() -> dict:
    out = {}
    for line in CONSTS.read_text(encoding="utf-8").splitlines():
        m = re.match(r"%define\s+(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\s*(?:;.*)?$", line)
        if m:
            out[m.group(1)] = int(m.group(2), 0)
    return out


def main() -> int:
    consts = load_consts()
    rows, unknown = [], []
    started = False
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        line = raw.split(";")[0].strip()
        if line.startswith(LABEL):
            started = True
            continue
        if not started or not line:
            continue
        m = re.match(r"^db\s+(-1|\w+)$", line)
        if not m:
            break
        tok = m.group(1)
        if tok == "-1":
            rows.append(("0xFF", "end"))
            break
        if tok not in consts:
            unknown.append(tok)
            continue
        rows.append((f"0x{consts[tok]:02X}", tok))
    if unknown:
        sys.stderr.write(f"gen_unknown_list: unresolved species {unknown}\n")
        return 1
    if len(rows) < 2 or rows[-1][1] != "end":
        sys.stderr.write("gen_unknown_list: list did not end with the -1 sentinel\n")
        return 1

    out = [
        "; unknown_list.inc — generated by tools/generators/gen_unknown_list.py.",
        "; DO NOT EDIT BY HAND.",
        f"; pret data/pokemon/unknown_list.asm — a $FF-terminated species list read only",
        f"; by engine/pokemon/evos_moves.asm:Func_3b0a2. {len(rows) - 1} species + sentinel.",
        "",
        f"global {LABEL}",
        f"{LABEL}:",
    ]
    out += [f"    db {v}    ; {name}" for v, name in rows]
    out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(rows) - 1} species)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
