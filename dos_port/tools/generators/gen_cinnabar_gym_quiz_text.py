#!/usr/bin/env python3
"""gen_cinnabar_gym_quiz_text.py — generate dos_port/assets/cinnabar_gym_quiz_text.inc
(Tier 1 data).

pret engine/events/hidden_events/cinnabar_gym_quiz.asm carries 10 pure
`text_far _X / text_end` wrapper labels (the intro texts + the 6 quiz
questions + the wrong-answer line) and one MIXED label,
CinnabarGymQuizCorrectText, whose text_far intro is followed by a real
text_asm code tail (flag check + SFX). Reuses gen_battle_text.py's
charmap/memmap/far-text machinery, same shape as gen_pikachu_text.py:

  * The 10 pure wrappers are flattened directly under their own name (the
    port's flat TX_FAR model — no indirection needed when nothing follows
    text_end), exactly like gen_pikachu_text.py's ExpressionText.
  * CinnabarGymQuizCorrectText keeps its underscore-prefixed far body,
    `_CinnabarGymQuizCorrectText`, as a STANDALONE label (raw bytes, no
    flattening) because the hand-written carrier
    (src/engine/events/hidden_events/cinnabar_gym_quiz.asm) still needs a
    real `text_far _CinnabarGymQuizCorrectText` command byte + pointer ahead
    of its text_asm code tail — same pattern as
    src/engine/battle/effects.asm:ChargeMoveEffectText /
    assets/battle_text.inc:_ChargeMoveEffectText.

Carrier: dos_port/src/engine/events/hidden_events/cinnabar_gym_quiz.asm (the
pret mirror path).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "cinnabar_gym_quiz_text.inc"

QUIZ_SRC = ["engine/events/hidden_events/cinnabar_gym_quiz.asm"]

WRAPPER_WANT = {
    "CinnabarGymQuizDummyIntroText",
    "CinnabarGymQuizIntroText",
    "CinnabarGymQuizShortIntroText",
    "CinnabarGymQuizIncorrectText",
    "CinnabarQuizQuestionsText1",
    "CinnabarQuizQuestionsText2",
    "CinnabarQuizQuestionsText3",
    "CinnabarQuizQuestionsText4",
    "CinnabarQuizQuestionsText5",
    "CinnabarQuizQuestionsText6",
}
FAR_WANT = {"_CinnabarGymQuizCorrectText"}


def existing_labels() -> set:
    """Labels already emitted elsewhere — never define one global twice."""
    out = set()
    assets = ROOT / "dos_port" / "assets"
    for inc in assets.glob("*.inc"):
        if inc.name == OUT.name:
            continue
        out |= set(re.findall(r"^global (\w+)$", inc.read_text(), re.M))
    return out


def main() -> int:
    charmap = gbt.load_charmap()
    memmap = gbt.load_memmap()
    far_db = gbt.collect_far(charmap, memmap)

    missing_far = FAR_WANT - set(far_db)
    if missing_far:
        raise SystemExit(
            f"gen_cinnabar_gym_quiz_text: expected far labels missing: {sorted(missing_far)}")

    gbt.BATTLE_SRC = QUIZ_SRC             # retarget the wrapper collector
    wrappers = gbt.collect_wrappers(charmap, memmap, far_db)

    missing_wrap = WRAPPER_WANT - set(wrappers)
    if missing_wrap:
        raise SystemExit(
            f"gen_cinnabar_gym_quiz_text: expected wrappers missing from scan: {sorted(missing_wrap)}")

    skip = existing_labels()
    wrap_labels = sorted(WRAPPER_WANT - skip)
    far_labels = sorted(FAR_WANT - skip)
    if not wrap_labels and not far_labels:
        raise SystemExit("gen_cinnabar_gym_quiz_text: every wanted label is already emitted elsewhere")

    out = [
        "; cinnabar_gym_quiz_text.inc — generated by tools/generators/gen_cinnabar_gym_quiz_text.py.",
        "; DO NOT EDIT BY HAND.",
        "; Cinnabar gym quiz message streams (pret",
        "; engine/events/hidden_events/cinnabar_gym_quiz.asm), text_far flattened for the",
        f"; pure wrappers ({len(wrap_labels)}) plus the standalone far body CinnabarGymQuizCorrectText",
        "; needs ahead of its text_asm tail. section .data (see link.ld).",
        "",
        "section .data",
        "",
    ]
    for label in wrap_labels:
        b = wrappers[label]
        out.append(f"global {label}")
        out.append(f"{label}:")
        for i in range(0, len(b), 16):
            out.append("    db " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
        out.append(f"global {label}_ref")
        out.append(f"{label}_ref: dd {label}, {len(b)}   ; flat ptr + byte count")
    for label in far_labels:
        b = far_db[label]
        out.append(f"global {label}")
        out.append(f"{label}:")
        for i in range(0, len(b), 16):
            out.append("    db " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(wrap_labels)} wrapper(s), {len(far_labels)} far label(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
