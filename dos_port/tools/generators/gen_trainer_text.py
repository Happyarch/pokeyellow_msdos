#!/usr/bin/env python3
"""gen_trainer_text.py — generate dos_port/assets/trainer_text.inc (Tier 1 data).

The trainer-header engine's end-battle message (home/trainers.asm:
TrainerEndBattleText) opens with `text_far _TrainerNameText` — a far stream in
pret data/text/text_1.asm ("<wNameBuffer>: ") that prints the defeated trainer's
name before the win/lose text. The port keeps TrainerEndBattleText itself as a
hand-laid stream in src/home/trainers.asm (its text_asm tail is Tier-2 code),
with its TX_FAR operand as a 32-bit flat pointer at _TrainerNameText — so the
far body must exist as real data.

Reuses gen_battle_text.py's charmap / memmap / text-macro parser verbatim
(same model as gen_item_text.py / gen_menu_strings.py's menu_text.inc).
Emits, in section .data, the far label(s) below with pret's exact byte stream
(text_ram wNameBuffer resolves to the port's gb_memmap.inc offset).

DO NOT EDIT the output by hand — re-run this generator.
Run from repo root or dos_port/.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "trainer_text.inc"

# Far labels consumed by src/home/trainers.asm.
TRAINER_FAR = [
    "_TrainerNameText",   # data/text/text_1.asm — "<wNameBuffer>: " name prefix
]


def main() -> int:
    far = gbt.collect_far(gbt.load_charmap(), gbt.load_memmap())
    out = [
        "; trainer_text.inc — generated by tools/generators/gen_trainer_text.py. DO NOT EDIT BY HAND.",
        "; Trainer-engine FAR message streams (pret data/text), flattened via",
        "; gen_battle_text.collect_far. %included by src/home/trainers.asm inside",
        "; section .data so the labels never land in an orphaned section (link.ld).",
        "",
    ]
    for label in TRAINER_FAR:
        if label not in far:
            sys.stderr.write(f"gen_trainer_text: missing far label {label}\n")
            return 1
        rows = [
            "    db " + ", ".join(f"0x{b:02X}" for b in far[label][k:k + 16])
            for k in range(0, len(far[label]), 16)
        ]
        out.append(f"{label}:\n" + "\n".join(rows))
    out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(TRAINER_FAR)} far labels)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
