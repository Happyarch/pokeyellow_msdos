#!/usr/bin/env python3
"""gen_pokedex_rating_text.py — generate dos_port/assets/pokedex_rating_text.inc
(Tier 1 data).

pret's engine/events/pokedex_rating.asm (DisplayDexRating) wraps 17 text
streams: DexCompletionText (Oak's-PC rating intro — two numeric fields via
text_decimal hDexRatingNumMonsSeen/hDexRatingNumMonsOwned) and the 16
DexRatingText_Own<N>To<M> bands DexRatingsTable dispatches to. Every wrapper's
body is exactly `text_far _<Label>` + `text_end`; the `_<Label>::` bodies live
in the pret file text/pokedex_ratings.asm — NOT under data/text/, which is all
gen_battle_text.TEXT_SRC globs by default, so that list is extended here (only
for this run; gen_battle_text's own default is untouched by other generators
sharing its import).

Reuses gen_battle_text.py's charmap/memmap/far-text machinery (same pattern as
gen_pikachu_text.py); the wrapper bodies are parsed directly out of pret's
engine file rather than through collect_wrappers' name-pattern regex, because
DexRatingText_Own0To9 etc. do not match that scanner's `*Text(?:\\d*|_[0-9a-f]+)`
suffix rule (the `_Own0To9` tail is not purely hex digits) — same reason
gen_predef_text.py parses its own table's definitions directly instead of
reusing collect_wrappers.

Emits each label as one flattened, self-terminating byte stream (the port's
flat TX_FAR model, matching gen_pikachu_text.py's `<Label>` + `<Label>_ref`
shape).

Carrier: dos_port/src/engine/events/pokedex_rating.asm (the pret mirror path).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "pokedex_rating_text.inc"

PRET_FILE = ROOT / "engine" / "events" / "pokedex_rating.asm"

WANT = [
    "DexCompletionText",
    "DexRatingText_Own0To9",
    "DexRatingText_Own10To19",
    "DexRatingText_Own20To29",
    "DexRatingText_Own30To39",
    "DexRatingText_Own40To49",
    "DexRatingText_Own50To59",
    "DexRatingText_Own60To69",
    "DexRatingText_Own70To79",
    "DexRatingText_Own80To89",
    "DexRatingText_Own90To99",
    "DexRatingText_Own100To109",
    "DexRatingText_Own110To119",
    "DexRatingText_Own120To129",
    "DexRatingText_Own130To139",
    "DexRatingText_Own140To149",
    "DexRatingText_Own150To151",
]


def collect_wrapper_bodies():
    """Split pret's engine/events/pokedex_rating.asm into blank-line-separated
    blocks and grab the ones headed by a WANT label. Each such block is a
    single-colon `Label:` line followed by its `text_far` / `text_end` lines —
    unlike text/pokedex_ratings.asm's `_Label::` far bodies, which
    gbt.collect_far handles."""
    text = PRET_FILE.read_text(encoding="utf-8")
    want = set(WANT)
    bodies = {}
    for block in re.split(r'\n\s*\n', text):
        lines = block.splitlines()
        if not lines:
            continue
        m = re.match(r'(\w+):\s*$', lines[0].strip())
        if not m or m.group(1) not in want:
            continue
        bodies[m.group(1)] = lines[1:]
    missing = want - set(bodies)
    if missing:
        raise SystemExit(
            f"gen_pokedex_rating_text: no wrapper block found in {PRET_FILE} for "
            f"{sorted(missing)} — pret file shape changed, re-audit WANT")
    return bodies


def main() -> int:
    charmap = gbt.load_charmap()
    memmap = gbt.load_memmap()

    # text/pokedex_ratings.asm holds the `_<Label>::` far bodies our wrappers
    # point at; it is not under data/text/, so extend TEXT_SRC for this run.
    gbt.TEXT_SRC = list(gbt.TEXT_SRC) + [ROOT / "text" / "pokedex_ratings.asm"]
    far_db = gbt.collect_far(charmap, memmap)

    bodies = collect_wrapper_bodies()

    encoded = {}
    for label in WANT:
        far_name = "_" + label
        if far_name not in far_db:
            raise SystemExit(
                f"gen_pokedex_rating_text: {far_name!r} not found in "
                f"text/pokedex_ratings.asm far-text scan")
        try:
            encoded[label] = gbt.parse_body(bodies[label], charmap, memmap, far_db)
        except (KeyError, ValueError) as e:
            raise SystemExit(f"gen_pokedex_rating_text: {label}: {e}")

    out = [
        "; pokedex_rating_text.inc — generated by "
        "tools/generators/gen_pokedex_rating_text.py. DO NOT EDIT BY HAND.",
        "; DisplayDexRating's 17 text_far streams (pret "
        "engine/events/pokedex_rating.asm wrappers over text/pokedex_ratings.asm),",
        f"; text_far flattened. {len(encoded)} label(s). section .data (see link.ld).",
        "",
        "section .data",
        "",
    ]
    for label in WANT:
        b = encoded[label]
        out.append(f"global {label}")
        out.append(f"{label}:")
        for i in range(0, len(b), 16):
            out.append("    db " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]))
        out.append(f"global {label}_ref")
        out.append(f"{label}_ref: dd {label}, {len(b)}   ; flat ptr + byte count")
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(encoded)} label(s), total "
          f"{sum(len(b) for b in encoded.values())} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
