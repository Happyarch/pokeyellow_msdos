#!/usr/bin/env python3
"""Generate the Game Boy Printer graphics assets.

Emits dos_port/assets/printer_gfx.inc containing hp.1bpp, lv.1bpp, and 01.2bpp
from gfx/printer/.
All data is read byte-for-byte from the read-only pret source tree.
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_globals import insert_globals

ROOT = Path(__file__).resolve().parents[3]
ASSETS = ROOT / "dos_port" / "assets"
GFX = ROOT / "gfx" / "printer"

HDR = "; printer_gfx.inc — generated by tools/generators/gen_printer_gfx_inc.py. DO NOT EDIT BY HAND."

GFX_BLOBS = [
    # (label, filename, expected_size, comment)
    (
        "GFX_ea563",
        "hp.1bpp",
        8,
        "Printer HP icon 1bpp -> 8 bytes",
    ),
    (
        "GFX_ea56b",
        "lv.1bpp",
        8,
        "Printer LV icon 1bpp -> 8 bytes",
    ),
    (
        "GFX_ea597",
        "01.2bpp",
        32,
        "Printer 0/1 debug tile graphics 2bpp -> 32 bytes",
    ),
]


def _db_lines(data: bytes) -> list[str]:
    return ["    db " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    lines = [HDR, ""]
    labels = []

    for label, fname, expected_sz, comment in GFX_BLOBS:
        src = GFX / fname
        if not src.exists():
            sys.exit(f"Missing source file: {src}")
        data = src.read_bytes()
        sz = len(data)
        assert sz == expected_sz, f"{fname}: size {sz} != expected {expected_sz}"

        labels.append(label)
        labels.append(f"{label}End")

        lines.append(f"; {comment}")
        lines.append(f"{label}:")
        lines.extend(_db_lines(data))
        lines.append(f"{label}End:")
        lines.append(f"{label.upper()}_SIZE equ {label}End - {label}")
        lines.append("")

    insert_globals(lines, labels, anchor=None)
    out_path = ASSETS / "printer_gfx.inc"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"Generated {out_path.name} with {len(GFX_BLOBS)} blobs.")


if __name__ == "__main__":
    main()
