def main():
    ASSETS.mkdir(parents=True, exist_ok=True)
    lines = [HDR, "", "section .data", ""]
    labels = []

    for label, seq, ref in STRINGS:
        data = _encode_sequence(seq)
        hexs = ", ".join(f"0x{b:02X}" for b in data)
        labels.append(label)
        lines.append(f"; pret: {ref}")
        lines.append(f"{label}: db {hexs}")
        lines.append("")

    # Collect _NoPokemonText via gen_battle_text.collect_far
    cm = gen_battle_text.load_charmap()
    mem = gen_battle_text.load_memmap()
    far = gen_battle_text.collect_far(cm, mem)
    if "_NoPokemonText" in far:
        labels.append("_NoPokemonText")
        hexs = ", ".join(f"0x{b:02X}" for b in far["_NoPokemonText"])
        lines.append("; pret: data/text/text_3.asm:_NoPokemonText")
        lines.append(f"_NoPokemonText: db {hexs}")
        lines.append("")

    insert_globals(lines, labels, anchor=None)
    out_path = ASSETS / "printer_strings.inc"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"Generated {out_path.name} with {len(labels)} string labels.")


if __name__ == "__main__":
    main()
