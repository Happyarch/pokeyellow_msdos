#!/usr/bin/env python3
"""gen_printer_strings.py — generate dos_port/assets/printer_strings.inc.

Generates the Game Boy Printer text strings from pret engine/printer/printer.asm,
engine/printer/printer2.asm, and data/text/text_3.asm (_NoPokemonText).
All strings are GB-charmap encoded via gb_text.encode / gen_battle_text.collect_far.
"""
from pathlib import Path
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_globals import insert_globals
import gb_text
import gen_battle_text

ROOT = Path(__file__).resolve().parents[3]
ASSETS = ROOT / "dos_port" / "assets"

HDR = "; printer_strings.inc — generated by tools/generators/gen_printer_strings.py. DO NOT EDIT BY HAND."

# Special tokens
NEXT = 0x4E       # "<NEXT>" line break
TERM = 0x50       # "@" string terminator
APOS_S = 0xBD     # "'s" charmap ligature
E_ACUTE = 0xBA    # "é" charmap glyph
ID_TOKEN = 0x73   # "<ID>" tile/glyph
NO_TOKEN = 0x74   # "№" tile/glyph


def _encode_sequence(seq: list) -> list[int]:
    """Given a list of strings and integer byte literals, return list[int]."""
    out = []
    for item in seq:
        if isinstance(item, str):
            out.extend(gb_text.encode(item))
        elif isinstance(item, int):
            out.append(item)
        elif isinstance(item, list):
            out.extend(item)
        else:
            raise TypeError(f"unexpected item {item!r}")
    return out


