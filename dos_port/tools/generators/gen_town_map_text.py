#!/usr/bin/env python3
"""gen_town_map_text.py — generate dos_port/assets/town_map_text.inc.

Emits the far text stream for the Town Map wall item:
  - _TownMapText (data/text/text_2.asm -> text/BluesHouse.asm:_BluesHouseTownMapText)

Consumed by dos_port/src/engine/events/hidden_events/town_map.asm.
DO NOT EDIT the output by hand — re-run this generator.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "town_map_text.inc"

LABELS = [
    "_TownMapText",
]


def fmt_bytes(label: str, data: list) -> str:
    rows = []
    for k in range(0, len(data), 16):
        rows.append("    db " + ", ".join(f"0x{b:02X}" for b in data[k:k + 16]))
    return f"global {label}\n{label}:\n" + "\n".join(rows)


def main() -> int:
    cm = gen_battle_text.load_charmap()
    mem = gen_battle_text.load_memmap()
    far = gen_battle_text.collect_far(cm, mem)

    out = [
        "; town_map_text.inc — generated by tools/generators/gen_town_map_text.py. DO NOT EDIT BY HAND.",
        "; Far-text stream for wall Town Map text_asm routine (pret data/text/text_2.asm).",
        "",
    ]
    for label in LABELS:
        if label not in far:
            sys.exit(f"gen_town_map_text: label {label} not found in pret data/text")
        out.append(fmt_bytes(label, far[label]))
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(LABELS)} label(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
