#!/usr/bin/env python3
"""gen_bills_house_pc_text.py — generate dos_port/assets/bills_house_pc_text.inc
(Tier 1 data).

pret engine/events/hidden_events/bills_house_pc.asm carries:
  * BillsMonListText — a raw db/next menu-list string ("EEVEE\\nFLAREON\\n
    JOLTEON\\nVAPOREON\\nCANCEL@"), not a text_far stream — hand-listed below,
    same shape as gen_battle_text.py's PLAIN STRINGS (no generic scanner
    matches pret's mixed `db "..."` / `next "..."` menu-list macro form).
  * BillsHousePokemonListText1 / BillsHousePokemonListText2 — 2 pure
    `text_far _X / text_end` wrappers with nothing else following, flattened
    directly under their own name (the port's flat TX_FAR model — no
    indirection needed when nothing follows text_end), exactly like
    gen_cinnabar_gym_quiz_text.py's 10 pure wrappers / gen_pikachu_text.py's
    ExpressionText.
  * `_BillsHouseInitiatedText` — kept as a STANDALONE far body (NOT
    flattened): the hand-written carrier
    (src/engine/events/hidden_events/bills_house_pc.asm) needs a real
    `text_far _BillsHouseInitiatedText` command byte + pointer ahead of its
    own text_promptbutton/text_asm code tail (BillsHouseInitiatedText is a
    predef_code TextPredefs row) — same pattern as
    src/engine/events/hidden_events/town_map.asm:TownMapText and
    vermilion_gym_trash.asm:VermilionGymTrashSuccessText1/Text3.

Carrier: dos_port/src/engine/events/hidden_events/bills_house_pc.asm (the pret
mirror path).

DO NOT EDIT the output by hand — re-run this generator. Run from repo root or
dos_port/.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text as gbt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "bills_house_pc_text.inc"

BPC_SRC = ["engine/events/hidden_events/bills_house_pc.asm"]

NEXT = 0x4E     # "<NEXT>" — line break
TERM = 0x50     # "@"      — string terminator

BILLS_MON_LIST = [
    ("BillsMonListText",
     ["EEVEE", NEXT, "FLAREON", NEXT, "JOLTEON", NEXT, "VAPOREON", NEXT, "CANCEL", TERM]),
]

FAR_WANT = {"_BillsHouseInitiatedText"}
WRAPPER_WANT = {"BillsHousePokemonListText1", "BillsHousePokemonListText2"}


def encode_parts_pret(parts, cm):
    out = []
    for p in parts:
        if isinstance(p, int):
            out.append(p)
        else:
            out.extend(gbt.encode(p, cm))
    return out


def main() -> int:
    cm = gbt.load_charmap()
    memmap = gbt.load_memmap()
    far_db = gbt.collect_far(cm, memmap)

    missing_far = FAR_WANT - set(far_db)
    if missing_far:
        raise SystemExit(
            f"gen_bills_house_pc_text: expected far labels missing: {sorted(missing_far)}")

    gbt.BATTLE_SRC = BPC_SRC   # retarget the wrapper collector at bills_house_pc.asm
    wrappers = gbt.collect_wrappers(cm, memmap, far_db)

    missing_wrap = WRAPPER_WANT - set(wrappers)
    if missing_wrap:
        raise SystemExit(
            f"gen_bills_house_pc_text: expected wrappers missing from scan: {sorted(missing_wrap)}")

    out = [
        "; bills_house_pc_text.inc — generated by tools/generators/gen_bills_house_pc_text.py.",
        "; DO NOT EDIT BY HAND.",
        "; Bills House PC text data (pret engine/events/hidden_events/bills_house_pc.asm):",
        "; the Eevee-evolution menu-list string, the 2 pure text_far wrappers (flattened),",
        "; and the standalone _BillsHouseInitiatedText far body the hand-written carrier's",
        "; text_far command references. section .data (see link.ld).",
        "",
        "section .data",
        "",
    ]

    for label, parts in BILLS_MON_LIST:
        b = encode_parts_pret(parts, cm)
        out.append(f"global {label}")
        out.append(f"{label}: db " + ", ".join(f"0x{x:02X}" for x in b))
    out.append("")

    for label in sorted(FAR_WANT):
        out.append(gbt.fmt(label, far_db[label]))
        out.append("")

    for label in sorted(WRAPPER_WANT):
        out.append(gbt.fmt(label, wrappers[label]))
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(BILLS_MON_LIST)} list(s), {len(FAR_WANT)} far stream(s), "
          f"{len(WRAPPER_WANT)} wrapper(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
