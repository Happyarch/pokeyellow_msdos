#!/usr/bin/env python3
"""gen_vermilion_gym_trash_text.py — generate dos_port/assets/vermilion_gym_trash_text.inc.

Emits the far text streams for the Vermilion Gym trash can events:
  - _VermilionGymTrashSuccessText1 (data/text/text_2.asm)
  - _VermilionGymTrashSuccessText3 (data/text/text_2.asm)
  - _VermilionGymTrashFailText     (data/text/text_2.asm)

Consumed by dos_port/src/engine/events/hidden_events/vermilion_gym_trash.asm.
DO NOT EDIT the output by hand — re-run this generator.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_battle_text  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "dos_port" / "assets" / "vermilion_gym_trash_text.inc"

LABELS = [
    "_VermilionGymTrashSuccessText1",
    "_VermilionGymTrashSuccessText3",
    "_VermilionGymTrashFailText",
]


def fmt_bytes(label: str, data: list) -> str:
    rows = []
    for k in range(0, len(data), 16):
        rows.append("    db " + ", ".join(f"0x{b:02X}" for b in data[k:k + 16]))
    return f"global {label}\n{label}:\n" + "\n".join(rows)


def main() -> int:
    cm = gen_battle_text.load_charmap()
    mem = gen_battle_text.load_memmap()
    far = gen_battle_text.collect_far(cm, mem)

    out = [
        "; vermilion_gym_trash_text.inc — generated by tools/generators/gen_vermilion_gym_trash_text.py. DO NOT EDIT BY HAND.",
        "; Far-text streams for Vermilion Gym trash can text_asm routines (pret data/text/text_2.asm).",
        "",
    ]
    for label in LABELS:
        if label not in far:
            sys.exit(f"gen_vermilion_gym_trash_text: label {label} not found in pret data/text")
        out.append(fmt_bytes(label, far[label]))
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(LABELS)} label(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
