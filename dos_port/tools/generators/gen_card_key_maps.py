#!/usr/bin/env python3
"""gen_card_key_maps.py — generate dos_port/assets/card_key_maps.inc.

Extracts SilphCoMapList from pret data/events/card_key_maps.asm.
Consumed via %include by dos_port/src/engine/events/card_key.asm.

DO NOT EDIT the output by hand — re-run this generator.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PRET_SRC = ROOT / "data" / "events" / "card_key_maps.asm"
OUT = ROOT / "dos_port" / "assets" / "card_key_maps.inc"

LABEL_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)::?\s*$")


def convert(row: str) -> str:
    body = row[3:].split(";")[0].strip()
    parts = [p.strip() for p in body.split(",")]
    conv = []
    for p in parts:
        if re.fullmatch(r"\$[0-9a-fA-F]+", p):
            conv.append("0x" + p[1:].upper())
        elif p == "-1":
            conv.append("0xFF")
        else:
            conv.append(p)
    return "    db " + ", ".join(conv)


def main() -> int:
    if not PRET_SRC.exists():
        sys.exit(f"gen_card_key_maps: {PRET_SRC} does not exist")

    rows = []
    in_label = False
    for raw in PRET_SRC.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        m = LABEL_RE.match(line)
        if m:
            if m.group(1) == "SilphCoMapList":
                in_label = True
            else:
                in_label = False
            continue
        if not in_label or not line or line.startswith(";"):
            continue
        if line.startswith("db "):
            rows.append(convert(line))
        else:
            in_label = False

    if not rows:
        sys.exit(f"gen_card_key_maps: extracted 0 rows for SilphCoMapList")

    out = [
        "; card_key_maps.inc — generated by tools/generators/gen_card_key_maps.py. DO NOT EDIT BY HAND.",
        "; Silph Co. elevator/stair map list (pret data/events/card_key_maps.asm:SilphCoMapList).",
        "",
        "global SilphCoMapList",
        "SilphCoMapList:",
    ]
    out.extend(rows)
    out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} row(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
