-- pc.lua — shared entry flow for the Bill's-PC box scenarios (bills_pc_ops /
-- box_change_roundtrip): boot → seeded new game → bedroom → Pallet Town →
-- Route 1 → Viridian City → the Pokémon Center → the PC in the top-right
-- corner → "SOMEONE's PC" → the Bill's PC box menu on screen.
--
-- This walks the REAL overworld (no warp seeding) so the scenario enters
-- BillsPC_ through the genuine PC main-menu handoff — the path that sets
-- BIT_USING_GENERIC_PC and BIT_NO_MENU_BUTTON_SOUND, the same state the
-- port's RunBillsPCTest harness mimics (see the sram-emulation memory's
-- harness-traps section).
--
-- NAVIGATION MODEL — target square + runtime re-planning, not fixed steps.
-- The passable grids below are derived from the pret map data (maps/*.blk +
-- gfx/blocksets/*.bst + the coll_tiles lists; a square is enterable iff the
-- bottom-left 8x8 tile of its 16x16 block is in the tileset's list — pret
-- collision reads exactly that tile, see engine/overworld/player_state.asm
-- _GetTileAndCoordsInFrontOfPlayer's per-facing lda_coord picks).
-- Regenerate with tools/mgba_harness/gen_walk_grids.py after any map edit.
-- Ledge tiles are absent from the lists, so ledges read as walls — correct
-- for this northbound walk.
--
-- Why re-planning: a fixed step list wedges when something parks on it. The
-- first bills_pc_ops runs deterministically hung at Viridian (30,21)→(30,20):
-- tile passable, no sprite at the square in ANY probe history — but in the
-- scenario's own input history a blocker (RNG-walked NPC or the slot-15
-- Pikachu sprite, which trails the player even pre-lab) parked there for
-- 6000+ frames, and retry-in-place replayed the same wall forever. goto_xy
-- marks the stalled square avoided, BFSes a fresh path from where it stands,
-- and only clears its avoid set once it actually moves. mGBA is
-- deterministic, so whatever detours a run takes, its golden reproduces
-- byte-identically.
--
-- Seeding: the full seed.debug_new_game happens INSIDE the Center, standing
-- at the PC — after all walking. battle.lua measured that seeding in the
-- bedroom broke the first walk step; nothing before the PC reads the
-- party/bag, and wGrassRate=0 (written on arrival at Route 1) is all the
-- walk itself needs (no wild encounters on the way).

