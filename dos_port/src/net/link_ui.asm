; ===========================================================================
; link_ui.asm — link-cable transport-select + connection-book UI. Port-only,
; NO PRET COUNTERPART (link cable plan Stage 5 step 3): the GB has a physical
; cable and never showed a "how will you link" menu or a saved-connection
; book — those only exist because the port has to pick a TRANSPORT (a real
; serial cable has none of that ambiguity) and remember addresses across
; reboots. Every routine/label here is a bespoke lowercase port name except
; the two contractual entry points CableClubNPC calls, which stay mixed-case
; to match the port's other HAL-boundary entry points (NetInit, NetHAL_*).
;
; CONTRACTS THIS FILE CONSUMES (read their own headers, not just this one):
;   kbd_text_edit  — src/input/kbd_text.asm. In: ESI=GB-space dest, BL=max
;                    len, BH=charset class, EDX=GB-space tilemap echo pos.
;                    Out: AL=1 commit / 0 cancel, dest '@'-terminated either
;                    way. IMPORTANT (verified by reading the source, not
;                    assumed): it does NOT seed from the dest's prior content
;                    — .entry unconditionally writes the terminator at offset
;                    0 and zeroes its internal length counter, so every call
;                    starts the field EMPTY. EDIT therefore starts blank too
;                    (see lu_edit_entry) — this is the "empty start is
;                    acceptable" branch the step-3 spec names, not the
;                    in-place-seed branch; reported to root per the spec's
;                    report format.
;   linkbook_load/store/record/loaded/book_image — src/net/link_book.asm.
;   g_net_transport/g_net_com_sel/NetInit — src/net/net_hal.asm.
;   LinkUIStr_* — assets/link_ui_strings.inc (generated by
;                 tools/generators/gen_link_ui_strings.py; two entries this
;                 step added — LinkUIStr_NoPort, LinkUIStr_NotInBuild — plus
;                 LinkUIStr_Com1..4 for the COM-pick menu).
;
; SURFACE / WINDOW MODEL — copied from src/engine/menus/link_menu.asm's
; LinkMenu precedent (its own header names this "WINDOW/CANVAS model"):
;   * A small box is staged into the stride-20 wTileMap scratch (box-relative
;     coords via the LUB() macro below, exactly LinkMenu's LMB()), mirrored
;     into GB_TILEMAP0 (lu_mirror, byte-for-byte LinkMenu's lm_link_mirror),
;     and shown as a SUB-RECT window via add_window (lu_show_window, byte-
;     for-byte LinkMenu's lm_link_show_window) — an OVERLAY appended on top
;     of whatever CableClubNPC's own PrintText dialog already has up, not a
;     full takeover. Box geometry is UI_LINK_MENU's own (assets/
;     ui_layout_menus.inc): 15x10 exterior / 13x8 interior — the SAME window
;     LinkMenu itself uses a moment later in the same call chain, reused
;     rather than inventing new geometry (this step has no sidecar entry to
;     derive one from, and LinkMenu's box is exactly the "small dialog box
;     over the overworld" this UI also wants).
;   * ONE window descriptor is added for this call's entire lifetime
;     (lu_show_window runs exactly once, from LinkTransportSelect); every
;     screen transition after that just redraws the wTileMap scratch and
;     calls lu_mirror again — never add_window again, which would grow
;     g_window_count on every transport<->book round trip.
;   * Three long strings (19/14/19 chars) don't fit the 13-col interior in
;     one line; the generator splits them with an embedded <NEXT> instead of
;     widening the box (see gen_link_ui_strings.py's header for why).
;   * kbd_text_edit's own `.draw` loop runs a self-contained per-frame
;     DelayFrame pump with no knowledge of this file's mirror step, so a
;     naive box-relative (LUB) echo position would only reach the screen
;     once the widget exits (nothing re-mirrors wTileMap->GB_TILEMAP0 while
;     it types). Fix: pass kbd_text_edit a NATIVE tilemap position instead —
;     LUN() below computes GB_TILEMAP0 + row*32 + col directly. Since our
;     box's scratch (0,0) already 1:1-maps onto GB_TILEMAP0 (0,0) via
;     lu_mirror's own blit, a LUN() position is numerically the "same cell"
;     a LUB() position would mirror to — so the field's live echo (and its
;     ClearScreenArea blank + cursor tile) lands directly in the tilemap our
;     window already sources from, no extra mirror call needed while typing.
;     ClearScreenArea's own SCREEN_WIDTH(40)-stride row-advance (see its
;     header in home/copy2.asm) is irrelevant here because kbd_text_edit only
;     ever clears ONE row (BH=1) — no row-advance ever executes.
;   * YesNoChoice (home/yes_no.asm, DELETE's confirm) manages its own
;     wTileMap-origin save/restore AND window save/restore, and its own
;     mirror target is GB_TILEMAP0 row 16 (YN_SROW, text_box.asm) — clear of
;     this file's rows 0-9. So it can be called directly while this file's
;     own window is still up: it draws on top, then fully undoes itself
;     (wTileMap content and window count both restored to what they were),
;     with no coordination needed on this side beyond redrawing next
;     (already the practice on every other screen transition here).
;
; MENU MECHANICS — same wTopMenuItemY/X + wMaxMenuItem + wMenuWatchedKeys +
; wLastMenuItem + menu_item_step + menu_redraw_cb + HandleMenuInput pattern
; LinkMenu uses (home/window.asm). Dispatch here is plain "AL bit tests +
; wCurrentMenuItem compares" — LinkMenu's extra "convert an A on the CANCEL
; row into a synthetic B" step exists only to shape the byte it exchanges
; with a serial peer (link_menu.asm:.asm_f586b) and does not apply: nothing
; here talks to a peer, so a CANCEL row is just an ordinary item that jumps
; to the same place B does.
;
; ADDRESS TEXT STAGING — kbd_text_edit's dest must be a GB-space (EBP-
; relative) offset; book_image (link_book.asm) is flat port-only memory, not
; reachable that way. Text is staged through wStringBuffer (pret ram/
; wram.asm: ds NAME_BUFFER_LENGTH = 20 bytes; PrintStatText's GB-space
; scratch, and the same buffer engine/menus/naming_screen.asm borrows for
; its own unrelated text entry) and only copied into book_image on a
; successful commit. NAME_BUFFER_LENGTH=20 caps the address field at
; LU_ADDR_MAX=19 characters (20 minus the terminator) — enough for common
; addresses ("192.168.1.100:12345" is 19) but NOT the absolute worst case
; ("255.255.255.255:65535" is 21); flagged as an open question in the step-3
; report rather than carving a new port-only WRAM region unilaterally.
;
; Build check: nasm -f coff -I include/ -I . -o /dev/null src/net/link_ui.asm
;              (from dos_port/)
; ===========================================================================

