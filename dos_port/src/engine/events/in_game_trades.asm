; ===========================================================================
; in_game_trades.asm — pret mirror of engine/events/in_game_trades.asm.
;
; DoInGameTradeDialogue drives the six NPC trades (ROUTE_11_GATE_2F,
; ROUTE_2_TRADE_HOUSE, CINNABAR_LAB_TRADE_ROOM, CINNABAR_LAB_FOSSIL_ROOM,
; ROUTE_18_GATE_2F, UNDERGROUND_PATH_ROUTE_5): it reads the TradeMons row
; selected by wWhichTrade, asks YES/NO, runs the party menu, swaps the mon and
; prints the dialogset's message.
;
; TWO-TIER RULE (CLAUDE.md):
;   * TradeMons and InGameTrade_TrainerString are pret `npctrade` / `dname`
;     rows — charmap-encoded names, i.e. Tier-1 DATA, generated by
;     tools/generators/gen_trades.py. They land in DIFFERENT files because pret
;     defines them in different files: TradeMons is a data/events/ label and
;     lives in src/data/events/trades.asm (externed here), while
;     InGameTrade_TrainerString is defined in this file and is %included below
;     from assets/trade_trainer_string.inc.
;   * The 17 far text streams are generated by
;     tools/generators/gen_overworld_strings.py into
;     assets/in_game_trade_text.inc. This file holds only the Tier-2 code and
;     pret's `text_far` wrappers.
;
; Register map (CLAUDE.md): A->AL, B->BH, C->BL, DE->EDX, HL->ESI, EBP = GB
; base. GB memory is [ebp + SYM]; flat program-image data (TradeMons, the text
; streams, the pointer tables) is addressed as [label] / [esi] with no EBP bias.
;
; THE ADDRESS-SPACE SPLIT IS THE WHOLE STORY OF THIS FILE. On the GB, TradeMons
; and InGameTrade_TrainerString live in a ROM bank mapped INSIDE the 16-bit GB
; address space, so pret's `call CopyData` is a GB->GB copy. In the port those
; tables are flat program-image .data outside the EBP window, and
; home/copy.asm:CopyData does `lea esi,[ebp+esi]` on its source, so it
; structurally cannot express a flat->GB copy. Every such site below is an
; inline `rep movsb` under a DEVIATION, following the precedent in
; src/engine/battle/draw_hud_pokeball_gfx.asm and
; src/engine/menus/draw_badges.asm. The GB->GB copies still go through
; CopyData / InGameTrade_CopyData exactly as pret does.
; ===========================================================================

