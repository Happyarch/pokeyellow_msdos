section .text

; ---------------------------------------------------------------------------
; DoInGameTradeDialogue — trigger the trade offer/action specified by wWhichTrade.
;
; DEVIATION{class=data-model; pret=engine/events/in_game_trades.asm:DoInGameTradeDialogue; behavior=the selected TradeMons nickname is copied to wInGameTradeMonNick by an inline rep movsb instead of by CopyData, and the chosen TradeTextPointersN table address is held in the port-local 32-bit slot wInGameTradeTextPointerTablePointer32 instead of the two GB bytes at wInGameTradeTextPointerTablePointer CD10; evidence=TradeMons is a flat program-image label outside the EBP window while home/copy.asm CopyData biases its source with lea esi ebp+esi so the two address spaces cannot meet through it, and a 32-bit flat table address does not fit in the two WRAM bytes pret uses for a 16-bit ROM pointer - those bytes are read only by this routine; lifetime=permanent while ROM data lives outside the emulated GB address space}
; ---------------------------------------------------------------------------
DoInGameTradeDialogue:
    call SaveScreenTilesToBuffer2
    mov esi, TradeMons                          ; ld hl, TradeMons (FLAT program-image data)
    mov al, [ebp + wWhichTrade]                 ; ld a, [wWhichTrade]
    mov bx, 0xe                                 ; ld bc, $e  (3 + NAME_LENGTH row stride)
    call AddNTimes                              ; esi += $e * al (address-space agnostic)

    mov al, [esi]                               ; ld a, [hli]
    inc esi
    mov [ebp + wInGameTradeGiveMonSpecies], al
    mov al, [esi]                               ; ld a, [hli]
    inc esi
    mov [ebp + wInGameTradeReceiveMonSpecies], al
    mov al, [esi]                               ; ld a, [hli] — the dialogset
    inc esi
    push eax                                    ; push af

    ; ld de, wInGameTradeMonNick / ld bc, NAME_LENGTH / call CopyData
    ; Flat source -> GB destination: inline (see the file header DEVIATION).
    push edi
    mov bx, NAME_LENGTH                         ; ld bc, NAME_LENGTH
    mov edx, wInGameTradeMonNick                ; ld de, wInGameTradeMonNick
    lea edi, [ebp + edx]
    mov ecx, NAME_LENGTH
    rep movsb                                   ; ESI advances as pret's HL does
    pop edi

    pop eax                                     ; pop af — al = dialogset

    ; ld l,a / ld h,0 / ld de, InGameTradeTextPointers / add hl,hl / add hl,de
    ; / ld a,[hli] -> ptr lo / ld a,[hl] -> ptr hi.  pret's dw table becomes dd
    ; here, so the *2 index becomes *4 and the pointer is one dword.
    movzx eax, al
    mov eax, [InGameTradeTextPointers + eax*4]
    mov [wInGameTradeTextPointerTablePointer32], eax

    mov al, [ebp + wInGameTradeGiveMonSpecies]
    mov edx, wInGameTradeGiveMonName            ; ld de, wInGameTradeGiveMonName
    call InGameTrade_GetMonName
    mov al, [ebp + wInGameTradeReceiveMonSpecies]
    mov edx, wInGameTradeReceiveMonName
    call InGameTrade_GetMonName

    mov byte [ebp + wInGameTradeTextPointerTableIndex], TRADETEXT_AFTER_TRADE
    mov bh, FLAG_TEST                           ; ld b, FLAG_TEST
    call InGameTrade_FlagActionPredef
    mov al, cl                                  ; ld a, c  (FlagAction returns the bit in CL)
    test al, al                                 ; and a
    jnz .printText

; if the trade hasn't been done yet
    mov byte [ebp + wInGameTradeTextPointerTableIndex], TRADETEXT_WANNA_TRADE
    call .printText
    mov byte [ebp + wInGameTradeTextPointerTableIndex], TRADETEXT_NO_TRADE
    call YesNoChoice
    mov al, [ebp + wCurrentMenuItem]
    test al, al                                 ; and a
    jnz .printText
    call InGameTrade_DoTrade
    jc .printText                               ; jr c, .printText
    mov esi, TradedForText                      ; ld hl, TradedForText (flat)
    call PrintText

.printText:
    ; pret walks wInGameTradeTextPointerTableIndex downwards with two `ld a,[hld]`
    ; to pick up the 16-bit table pointer at wInGameTradeTextPointerTablePointer,
    ; then `add hl,de` twice (index * 2) and loads the 16-bit text pointer.
    ; Flat model: one dword slot, stride 4.
    movzx edx, byte [ebp + wInGameTradeTextPointerTableIndex] ; ld e,a / ld d,0
    mov esi, [wInGameTradeTextPointerTablePointer32]
    mov esi, [esi + edx*4]
    jmp PrintText                               ; jp PrintText

; ---------------------------------------------------------------------------
; InGameTrade_GetMonName — copies the name of species AL to EDX (pret's comment
; says "to hl", but the routine writes to de).
; ---------------------------------------------------------------------------
InGameTrade_GetMonName:
    push edx                                    ; push de
    mov [ebp + wNamedObjectIndex], al           ; ld [wNamedObjectIndex], a
    call GetMonName
    mov esi, wNameBuffer                        ; ld hl, wNameBuffer (GB offset)
    pop edx                                     ; pop de
    mov bx, NAME_LENGTH                         ; ld bc, NAME_LENGTH
    jmp CopyData                                ; jp CopyData — GB -> GB

; ---------------------------------------------------------------------------
; InGameTrade_DoTrade — run the party menu, verify the offered mon, swap it.
; Returns CF set on failure (with wInGameTradeTextPointerTableIndex set to the
; message to print), CF clear on success.
; ---------------------------------------------------------------------------
InGameTrade_DoTrade:
    xor al, al                                  ; xor a ; NORMAL_PARTY_MENU
    mov [ebp + wPartyMenuTypeOrMessageID], al
    dec al                                      ; dec a -> $FF
    mov [ebp + wUpdateSpritesEnabled], al
    call DisplayPartyMenu
    pushfd                                      ; push af — only F is live (A is
                                                ; overwritten below before any read)
    call InGameTrade_RestoreScreen
    popfd                                       ; pop af
    mov al, TRADETEXT_NO_TRADE                  ; ld a, TRADETEXT_NO_TRADE (no flag change)
    jc .tradeFailed                             ; jp c, .tradeFailed — no mon selected

    mov al, [ebp + wInGameTradeGiveMonSpecies]
    mov bh, al                                  ; ld b, a
    mov al, [ebp + wCurPartySpecies]
    cmp al, bh                                  ; cp b
    mov al, TRADETEXT_WRONG_MON                 ; (mov imm preserves flags)
    jnz .tradeFailed                            ; jr nz, .tradeFailed

    mov al, [ebp + wWhichPokemon]
    mov esi, wPartyMon1Level                    ; ld hl, wPartyMon1Level (GB offset)
    mov bx, PARTYMON_STRUCT_LENGTH
    call AddNTimes
    mov al, [ebp + esi]                         ; ld a, [hl]
    mov [ebp + wCurEnemyLevel], al

    mov bh, FLAG_SET                            ; ld b, FLAG_SET
    call InGameTrade_FlagActionPredef
    mov esi, ConnectCableText                   ; ld hl, ConnectCableText (flat)
    call PrintText

    movzx eax, byte [ebp + wWhichPokemon]
    push eax                                    ; push af (data, not flags)
    movzx eax, byte [ebp + wCurEnemyLevel]
    push eax                                    ; push af
    call LoadHpBarAndStatusTilePatterns
    call InGameTrade_PrepareTradeData
; DEVIATION{class=banking; pret=macros/predef.asm:predef; behavior=Predef dispatch replaced by a direct call, and A is left holding whatever the callee left rather than pret's parent ROM bank; evidence=pret Predef saves hLoadedROMBank with push af and restores it with pop af before returning so A holds a BANK NUMBER on return - not the predef id - and the flat DPMI model has no banks for that value to mean anything, plus the two values popped immediately after this site are read back from the stack not from A; lifetime=retired when PredefPointers is ported}
    call InternalClockTradeAnim                 ; predef InternalClockTradeAnim
    pop eax                                     ; pop af
    mov [ebp + wCurEnemyLevel], al
    pop eax                                     ; pop af
    mov [ebp + wWhichPokemon], al

    mov al, [ebp + wInGameTradeReceiveMonSpecies]
    mov [ebp + wCurPartySpecies], al
    xor al, al
    mov [ebp + wMonDataLocation], al            ; not used
    mov [ebp + wRemoveMonFromBox], al
    call RemovePokemon
    mov al, 0x80                                ; ld a, $80 ; prevent naming the mon
    mov [ebp + wMonDataLocation], al
    call AddPartyMon
    call InGameTrade_CopyDataToReceivedMon
    call InGameTrade_CheckForTradeEvo
    call ClearScreen
    call InGameTrade_RestoreScreen
    call RedrawMapView                          ; farcall RedrawMapView (bank switch is a flat no-op)
    and al, al                                  ; and a — clears CF for the success return
    mov al, TRADETEXT_THANKS                    ; (mov imm preserves flags)
    jmp .tradeSucceeded                         ; jr .tradeSucceeded

.tradeFailed:
    stc                                         ; scf
.tradeSucceeded:
    mov [ebp + wInGameTradeTextPointerTableIndex], al
    ret

; ---------------------------------------------------------------------------
; InGameTrade_RestoreScreen — restore the pre-party-menu screen and tilesets.
; ---------------------------------------------------------------------------
InGameTrade_RestoreScreen:
    call GBPalWhiteOutWithDelay3
    call RestoreScreenTilesAndReloadTilePatterns
    call ReloadTilesetTilePatterns
    call LoadScreenTilesFromBuffer2
    call Delay3
    call LoadGBPal
    mov bl, 10                                  ; ld c, 10 — DelayFrames' counter is
                                                ; 8 bits on the GB and stays 8 bits here
    call DelayFrames
    jmp LoadWildData                            ; farjp LoadWildData (flat no-op bank switch)

; ---------------------------------------------------------------------------
; InGameTrade_PrepareTradeData — fill the wTraded* mirror the trade animation
; and the received mon read back.
;
; DEVIATION{class=data-model; pret=engine/events/in_game_trades.asm:InGameTrade_PrepareTradeData; behavior=the two copies out of InGameTrade_TrainerString are inline rep movsb instead of InGameTrade_CopyData-CopyData; evidence=InGameTrade_TrainerString is a flat program-image label from the generated assets-trades.inc while home/copy.asm CopyData biases its source with lea esi ebp+esi so a flat source cannot be passed to it, the same split already taken in engine/battle/draw_hud_pokeball_gfx.asm and engine/menus/draw_badges.asm, and the byte sequence written is identical; lifetime=permanent while ROM data lives outside the emulated GB address space}
; ---------------------------------------------------------------------------
InGameTrade_PrepareTradeData:
    mov esi, wTradedPlayerMonSpecies            ; ld hl, wTradedPlayerMonSpecies
    mov al, [ebp + wInGameTradeGiveMonSpecies]
    mov [ebp + esi], al                         ; ld [hli], a — wTradedPlayerMonSpecies
    inc esi
    mov al, [ebp + wInGameTradeReceiveMonSpecies]
    mov [ebp + esi], al                         ; ld [hl], a  — wTradedEnemyMonSpecies

    mov esi, wPartyMonOT                        ; ld hl, wPartyMonOT
    mov bx, NAME_LENGTH
    mov al, [ebp + wWhichPokemon]
    call AddNTimes
    mov edx, wTradedPlayerMonOT                 ; ld de, wTradedPlayerMonOT
    mov bx, NAME_LENGTH
    call InGameTrade_CopyData                   ; GB -> GB

    ; ld hl, InGameTrade_TrainerString (FLAT) / ld de, wTradedEnemyMonOT
    ; / call InGameTrade_CopyData  — inlined, see the DEVIATION above.
    push edi
    mov esi, InGameTrade_TrainerString
    mov ecx, NAME_LENGTH
    lea edi, [ebp + wTradedEnemyMonOT]
    rep movsb
    ; ld de, wLinkEnemyTrainerName / call InGameTrade_CopyData — the second copy
    ; reuses the same flat source, exactly as pret's preserved hl does.
    mov esi, InGameTrade_TrainerString
    mov ecx, NAME_LENGTH
    lea edi, [ebp + wLinkEnemyTrainerName]
    rep movsb
    pop edi

    mov esi, wPartyMon1OTID                     ; ld hl, wPartyMon1OTID
    mov bx, PARTYMON_STRUCT_LENGTH
    mov al, [ebp + wWhichPokemon]
    call AddNTimes
    mov edx, wTradedPlayerMonOTID               ; ld de, wTradedPlayerMonOTID
    mov bx, 2                                   ; ld bc, $2
    call InGameTrade_CopyData                   ; GB -> GB (BX survives it)

    call Random
    mov esi, hRandomAdd                         ; ld hl, hRandomAdd (HRAM, GB offset)
    mov edx, wTradedEnemyMonOTID                ; ld de, wTradedEnemyMonOTID
    jmp CopyData                                ; jp CopyData — BX is still 2

; ---------------------------------------------------------------------------
; InGameTrade_CopyData — CopyData with HL/BC preserved.
; ---------------------------------------------------------------------------
InGameTrade_CopyData:
    push esi                                    ; push hl
    push ebx                                    ; push bc
    call CopyData
    pop ebx                                     ; pop bc
    pop esi                                     ; pop hl
    ret

; ---------------------------------------------------------------------------
; InGameTrade_CopyDataToReceivedMon — nickname / OT name / OT ID of the mon just
; added to the party.
;
; DEVIATION{class=data-model; pret=engine/events/in_game_trades.asm:InGameTrade_CopyDataToReceivedMon; behavior=the OT-name copy out of InGameTrade_TrainerString is an inline rep movsb instead of CopyData; evidence=InGameTrade_TrainerString is a flat program-image label from the generated assets-trades.inc and home/copy.asm CopyData biases its source with lea esi ebp+esi so it cannot take a flat source, while the destination and the 11 bytes written are unchanged; lifetime=permanent while ROM data lives outside the emulated GB address space}
; ---------------------------------------------------------------------------
InGameTrade_CopyDataToReceivedMon:
    mov esi, wPartyMonNicks                     ; ld hl, wPartyMonNicks
    mov bx, NAME_LENGTH
    call InGameTrade_GetReceivedMonPointer      ; -> edx = &nick of the new mon
    mov esi, wInGameTradeMonNick                ; ld hl, wInGameTradeMonNick
    mov bx, NAME_LENGTH
    call CopyData                               ; GB -> GB

    mov esi, wPartyMonOT                        ; ld hl, wPartyMonOT
    mov bx, NAME_LENGTH
    call InGameTrade_GetReceivedMonPointer      ; -> edx = &OT name of the new mon
    ; ld hl, InGameTrade_TrainerString (FLAT) / ld bc, NAME_LENGTH / call CopyData
    push edi
    mov esi, InGameTrade_TrainerString
    mov ecx, NAME_LENGTH
    movzx edi, dx
    lea edi, [ebp + edi]
    rep movsb
    pop edi

    mov esi, wPartyMon1OTID                     ; ld hl, wPartyMon1OTID
    mov bx, PARTYMON_STRUCT_LENGTH
    call InGameTrade_GetReceivedMonPointer      ; -> edx = &OT ID of the new mon
    mov esi, wTradedEnemyMonOTID                ; ld hl, wTradedEnemyMonOTID
    mov bx, 2                                   ; ld bc, 2
    jmp CopyData                                ; jp CopyData — GB -> GB

; ---------------------------------------------------------------------------
; InGameTrade_GetReceivedMonPointer — the received mon's index is
; (partyCount - 1), so this adds BX to ESI (partyCount - 1) times and moves the
; result to EDX.
; ---------------------------------------------------------------------------
InGameTrade_GetReceivedMonPointer:
    mov al, [ebp + wPartyCount]
    dec al                                      ; dec a
    call AddNTimes
    mov edx, esi                                ; ld e,l / ld d,h  (ESI is a GB offset < $10000)
    ret

; ---------------------------------------------------------------------------
; InGameTrade_FlagActionPredef — test/set this trade's completion flag.
;
; DEVIATION{class=banking; pret=macros/predef.asm:predef_jump; behavior=Predef dispatch replaced by a direct jmp to the FlagAction leaf, and A is left holding whatever the callee left rather than pret's parent ROM bank; evidence=pret Predef saves hLoadedROMBank with push af and restores it with pop af before returning so A holds a BANK NUMBER on return - not the predef id - and the flat DPMI model has no banks for that value to mean anything, plus FlagActionPredef's own first act is GetPredefRegisters which would overwrite ESI and EBX from the stale wPredefHL and wPredefBC slots - the same direct-leaf convention already used by home/trainers.asm TrainerFlagAction and engine/pokemon/evos_moves.asm; lifetime=retired when PredefPointers is ported}
;
; In:  BH = FLAG_TEST / FLAG_SET.   Out: CL = flag value (FLAG_TEST).
; ---------------------------------------------------------------------------
InGameTrade_FlagActionPredef:
    mov esi, wCompletedInGameTradeFlags         ; ld hl, wCompletedInGameTradeFlags
    mov al, [ebp + wWhichTrade]                 ; ld a, [wWhichTrade]
    mov cl, al                                  ; ld c, a
    jmp FlagAction                              ; predef_jump FlagActionPredef

; ---------------------------------------------------------------------------
; InGameTrade_CheckForTradeEvo — the four trade-evolution species.
; ---------------------------------------------------------------------------
InGameTrade_CheckForTradeEvo:
    mov al, [ebp + wInGameTradeReceiveMonSpecies]
    cmp al, KADABRA
    jz .tradeEvo
    cmp al, GRAVELER
    jz .tradeEvo
    cmp al, MACHOKE
    jz .tradeEvo
    cmp al, HAUNTER
    jz .tradeEvo
    ret

.tradeEvo:
    mov al, [ebp + wPartyCount]
    dec al                                      ; dec a
    mov [ebp + wWhichPokemon], al
    mov al, 1                                   ; ld a, $1
    mov [ebp + wForceEvolution], al
    mov al, LINK_STATE_TRADING
    mov [ebp + wLinkState], al
    call TryEvolvingMon                         ; callfar TryEvolvingMon (flat no-op bank switch)
    xor al, al                                  ; xor a ; LINK_STATE_NONE
    mov [ebp + wLinkState], al
    jmp PlayDefaultMusic                        ; jp PlayDefaultMusic

