; bills_house_pc.asm — Bill's House PC hidden-event handler and Eevee-evolution
; Pokémon list.
;
; Faithful translation of pret engine/events/hidden_events/bills_house_pc.asm.
; This is the hidden-object PC prop in Bill's house (data/events/hidden_events.asm:
; `hidden_event 1, 4, BillsHousePC, SPRITE_FACING_UP`) — the teleporter/cell-
; separator cutscene machine, NOT the box-storage PC UI
; (src/engine/pokemon/bills_pc.asm, a different pret file entirely reached from
; a different hidden-event handler, OpenBillsPCText/engine/pokemon/bills_pc.asm).
; BillsHousePC never calls into that box UI on either side, pret or port.
;
; Register map (SM83 -> x86): A->AL, BC->BX (B->BH, C->BL), HL->ESI.
; GB memory is [ebp + addr] (gb_memmap.inc).
;
; TWO-TIER RULE: BillsMonListText (Eevee/Flareon/Jolteon/Vaporeon/Cancel menu
; list) and the 2 pure `text_far _X / text_end` wrappers
; (BillsHousePokemonListText1/2) are Tier-1 data, generated by
; tools/generators/gen_bills_house_pc_text.py into
; assets/bills_house_pc_text.inc, %included below — NOT re-declared `global`
; here (see the note above the wrapper section).
;
; PREDEF_CODE / TEXT_ASM TRAP (src/data/text_predef_pointers.asm ids 48/49):
; BillsHouseInitiatedText and BillsHousePokemonList are both `predef_code` rows
; — DisplayTextID's TEXT_PREDEF branch does a bare `call esi` straight at the
; label (TEXT_ASM_ENTRY sentinel), so each label must be x86 CODE at offset 0.
; Both keep pret's own text_far/text_promptbutton/text_asm command bytes
; VERBATIM at a local `.stream` label instead of at the label's own offset 0,
; and the label itself becomes a three-instruction trampoline that does
; exactly what DisplayTextID's own `.notScriptEntry` path does with a stream
; (src/home/text_script.asm): select the overworld dialog projection, then
; PrintText_NoCreatingTextBox. TX_START_ASM inside `.stream` is dispatched by
; TextCommandProcessor's `.cmd_asm` (`push .next_cmd / jmp esi`), which is
; pret's `ld de, NextTextCommand / push de / jp hl` exactly, so each `.hook`
; runs under pret's own control-flow contract. Same pattern as
; src/engine/events/hidden_events/town_map.asm:TownMapText and
; vermilion_gym_trash.asm:VermilionGymTrashSuccessText1/Text3/
; VermilionGymTrashSuccessPlaySfx (the last one is the bare-text_asm shape,
; matching BillsHousePokemonList exactly).
;
; Build: nasm -f coff -I include/ -I . -D BUG_FIX_LEVEL=0 -o /dev/null \
;            src/engine/events/hidden_events/bills_house_pc.asm

bits 32

