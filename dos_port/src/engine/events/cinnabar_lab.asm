; Port-only presentation (mart class, prize pattern): the fossil list drawn on
; the 40-wide canvas is invisible until mirrored into GB_TILEMAP0 and published
; as a window descriptor (the compositor reads the window source, not wTileMap).
; The list shares no geometry with money (srow 20) or the prize menu (srow 1),
; so it gets a fresh slot; YN (srow 11) opens during the confirm.
FOSSIL_SROW equ 2            ; GB_TILEMAP0 mirror rows 2..9 (list 15xH, H<=8)
FOSSIL_LIST_W equ 15         ; box width in tiles (matches TextBoxBorder bl=13 + borders)
FOSSIL_MENU_WX equ 7         ; left-projected, same anchor as the prize menu
FOSSIL_MENU_WY equ 0
FOSSIL_MENU_CLIP equ 120     ; 15 tiles * 8
FOSSIL_MENU_MAXY equ 64      ; 8 rows * 8 (max height: 3 fossils -> bh+2 rows)

; Far text streams this file uses — pret text/CinnabarLabFossilRoom.asm, generated by
; tools/generators/gen_map_text.py (event_<stem>.inc namespace, so this file's
; "cinnabar_lab" stem never collides with src/scripts/cinnabar_lab.asm's own
; assets/map_text/CinnabarLab.inc).
section .data
%include "assets/map_text/event_cinnabar_lab.inc"

