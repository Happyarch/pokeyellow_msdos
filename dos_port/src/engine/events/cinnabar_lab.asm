; ---------------------------------------------------------------------------
; GiveFossilToCinnabarLab — pret ref: engine/events/cinnabar_lab.asm:1-72.
; In: wFilteredBagItems/wFilteredBagItemsCount already populated by the caller
;     (Lab4Script_GetFossilsInBag, scripts/cinnabar_lab_fossil_room.asm).
; ---------------------------------------------------------------------------
GiveFossilToCinnabarLab:
    or byte [ebp + wStatusFlags5], (1 << BIT_NO_TEXT_DELAY) ; ld hl, wStatusFlags5 / set BIT_NO_TEXT_DELAY, [hl]
    xor al, al                                    ; xor a
    mov [ebp + wCurrentMenuItem], al              ; ld [wCurrentMenuItem], a
    mov byte [ebp + wMenuWatchedKeys], PAD_A | PAD_B ; ld a, PAD_A | PAD_B / ld [wMenuWatchedKeys], a
    mov al, [ebp + wFilteredBagItemsCount]        ; ld a, [wFilteredBagItemsCount]
    dec al                                        ; dec a
    mov [ebp + wMaxMenuItem], al                  ; ld [wMaxMenuItem], a
    mov byte [ebp + wTopMenuItemY], 2             ; ld a, 2 / ld [wTopMenuItemY], a
    mov byte [ebp + wTopMenuItemX], 1             ; ld a, 1 / ld [wTopMenuItemX], a

    mov al, [ebp + wFilteredBagItemsCount]        ; ld a, [wFilteredBagItemsCount]
    dec al                                        ; dec a
    mov bx, 2                                     ; ld bc, 2
    mov esi, 3                                    ; ld hl, 3 — a plain scratch counter, NOT a coordinate
    call AddNTimes                                ; call AddNTimes — esi = 3 + 2*(count-1)
    mov eax, esi                                  ; dec l — ESI has no 8-bit sub-register in 32-bit mode,
    dec al                                        ;   so truncate through AL (reproduces pret's 8-bit wrap)
    mov bh, al                                    ; ld b, l
    mov bl, 0x0d                                  ; ld c, $d
    ; PROJ overworld-ui (fossil list box): GB(0,0) 15x(dynamic) --(anchor=top-LEFT, X+0, Y+0)--> wx=7 wy=0 clip=120 max_y=8*(3+2*(N-1))
    ; Canvas list drawing runs at the 40-wide canvas stride: force it around
    ; the border + entries (same trap the mart mirrors were built for).
    push dword [text_row_stride]
    mov dword [text_row_stride], SCREEN_TILES_W
    hlcoord 0, 0                                  ; hlcoord 0, 0
    call TextBoxBorder                            ; call TextBoxBorder
    call UpdateSprites                            ; call UpdateSprites
    call PrintFossilsInBag                        ; call PrintFossilsInBag
    pop dword [text_row_stride]
    call fossil_show_list_window                   ; mirror + idempotent publish (mart class)
    and byte [ebp + wStatusFlags5], ~(1 << BIT_NO_TEXT_DELAY) & 0xFF ; ld hl, wStatusFlags5 / res BIT_NO_TEXT_DELAY, [hl]
    ; Mart pattern (pokemart.asm): dialog pauses reset the window list via
    ; set_single_window unless this flag is set — without it the Sees/Takes
    ; prompts below tear down the fossil list mid-flow.
    mov byte [g_dialog_preserve_windows], 1
    ; PlaceMenuCursor addresses Y*stride+X: entries are double-spaced canvas
    ; rows, so drive input at the canvas stride with the two-row canvas step
    ; (prize pattern).
    mov dword [menu_item_step], 2 * SCREEN_TILES_W
    push dword [text_row_stride]
    mov dword [text_row_stride], SCREEN_TILES_W
    mov dword [menu_redraw_cb], fossil_list_mirror ; re-mirror per input frame (cursor moves)
    call HandleMenuInput                          ; call HandleMenuInput
    mov dword [menu_redraw_cb], 0
    pop dword [text_row_stride]
    test al, PAD_B                                ; bit B_PAD_B, a
    jnz .cancelledGivingFossil                    ; jr nz, .cancelledGivingFossil

    movzx edx, byte [ebp + wCurrentMenuItem]      ; ld a, [wCurrentMenuItem] / ld d, 0 / ld e, a
    lea esi, [wFilteredBagItems + edx]            ; ld hl, wFilteredBagItems / add hl, de
    mov al, [ebp + esi]                           ; ld a, [hl]
    mov [ebp + hItemToRemoveID], al               ; ldh [hItemToRemoveID], a
    cmp al, DOME_FOSSIL                           ; cp DOME_FOSSIL
    jz .choseDomeFossil                           ; jr z, .choseDomeFossil
    cmp al, HELIX_FOSSIL                          ; cp HELIX_FOSSIL
    jz .choseHelixFossil                          ; jr z, .choseHelixFossil
    mov bh, AERODACTYL                            ; ld b, AERODACTYL
    jmp .fossilSelected                           ; jr .fossilSelected
.choseHelixFossil:
    mov bh, OMANYTE                               ; ld b, OMANYTE
    jmp .fossilSelected                           ; jr .fossilSelected
.choseDomeFossil:
    mov bh, KABUTO                                ; ld b, KABUTO
.fossilSelected:
    mov [ebp + wFossilItem], al                   ; ld [wFossilItem], a
    mov al, bh                                    ; ld a, b
    mov [ebp + wFossilMon], al                    ; ld [wFossilMon], a
    call LoadFossilItemAndMonName                 ; call LoadFossilItemAndMonName
    mov esi, .ScientistSeesFossilText             ; ld hl, .ScientistSeesFossilText
    call PrintText                                ; call PrintText
    call YesNoChoice                              ; call YesNoChoice
    mov al, [ebp + wCurrentMenuItem]              ; ld a, [wCurrentMenuItem]
    test al, al                                   ; and a
    jnz .cancelledGivingFossil                    ; jr nz, .cancelledGivingFossil
    mov esi, .ScientistTakesFossilText            ; ld hl, .ScientistTakesFossilText
    call PrintText                                ; call PrintText
    mov al, [ebp + wFossilItem]                   ; ld a, [wFossilItem]
    mov [ebp + hItemToRemoveID], al               ; ldh [hItemToRemoveID], a
; DEVIATION{class=banking; pret=engine/events/cinnabar_lab.asm:GiveFossilToCinnabarLab; behavior=call RemoveItemByID directly instead of the pret farcall; evidence=the DPMI model is flat so every routine is always addressable and Bankswitch has no port counterpart, same convention every other farcall/farjp site in this tree uses; lifetime=permanent flat-memory boundary}
    call RemoveItemByID                           ; farcall RemoveItemByID
    mov esi, .GoForAWalkText                      ; ld hl, .GoForAWalkText
    call PrintText                                ; call PrintText
    SetEvents EVENT_GAVE_FOSSIL_TO_LAB, EVENT_LAB_STILL_REVIVING_FOSSIL
    ; Spec: teardown happens here — after the choice resolves, never earlier.
    ; Drops exactly the fossil list window; the dialog stays for
    ; HoldTextDisplayOpen, closed by CloseTextDisplay's hide_window.
    call fossil_drop_windows
    mov byte [g_dialog_preserve_windows], 0
    ret
.cancelledGivingFossil:
    mov esi, .ComeAgainText                       ; ld hl, .ComeAgainText
    call PrintText                                ; call PrintText
    call fossil_drop_windows
    mov byte [g_dialog_preserve_windows], 0
    ret

; ---------------------------------------------------------------------------
; Text wrappers — pret engine/events/cinnabar_lab.asm:74-91.
