; ---------------------------------------------------------------------------
; PrintFossilsInBag — pret ref: engine/events/cinnabar_lab.asm:94-113.
; Prints each fossil in the player's bag on a separate line of the menu.
; ---------------------------------------------------------------------------
PrintFossilsInBag:
    mov esi, wFilteredBagItems                   ; ld hl, wFilteredBagItems
    xor al, al                                    ; xor a
    mov [ebp + hItemCounter], al                  ; ldh [hItemCounter], a
.loop:
    mov al, [ebp + esi]                           ; ld a, [hli]
    lea esi, [esi + 1]
    cmp al, 0xff                                  ; cp $ff
    jnz .continue                                 ; ret z (inverted)
    ret
.continue:
    push esi                                      ; push hl
    mov [ebp + wNamedObjectIndex], al             ; ld [wNamedObjectIndex], a
    call GetItemName                              ; call GetItemName
    ; PROJ overworld-ui (fossil list box entries): GB(2,2) --(anchor=top-LEFT, X+0, Y+0)--> unchanged
    hlcoord 2, 2                                  ; hlcoord 2, 2
    movzx eax, byte [ebp + hItemCounter]          ; ldh a, [hItemCounter]
    mov bx, SCREEN_WIDTH * 2                      ; ld bc, SCREEN_WIDTH * 2
    call AddNTimes                                ; call AddNTimes
    lea eax, [ebp + wNameBuffer]                  ; ld de, wNameBuffer — PlaceString takes a flat ptr in EAX
    call PlaceString                              ; call PlaceString
    inc byte [ebp + hItemCounter]                 ; ld hl, hItemCounter / inc [hl]
    pop esi                                       ; pop hl
    jmp .loop                                     ; jr .loop

; ---------------------------------------------------------------------------
; LoadFossilItemAndMonName — pret ref: engine/events/cinnabar_lab.asm:115-123.
; Loads the names of the fossil item and the resulting mon.
; Out: wNameBuffer = mon name, wStringBuffer = mon name copy, wNameBuffer = item name
;      (matches pret: GetMonName+CopyToStringBuffer save the mon name into
;      wStringBuffer, then GetItemName overwrites wNameBuffer with the item name).
; ---------------------------------------------------------------------------
LoadFossilItemAndMonName:
    mov al, [ebp + wFossilMon]                    ; ld a, [wFossilMon]
    mov [ebp + wNamedObjectIndex], al             ; ld [wNamedObjectIndex], a
    call GetMonName                               ; call GetMonName
    ; Not a divergence from pret (output is identical either way): GetMonName
    ; (src/home/names.asm) has no documented EDX-out contract the way
    ; GetItemName/GetPartyMonName do (both state EDX=wNameBuffer on exit), so
    ; the port sets EDX explicitly here rather than relying on an incidental
    ; register value — matching the explicit-EDX pattern list_menu.asm already
    ; uses at its own GetXName / CopyToStringBuffer call site.
    mov edx, wNameBuffer                          ; ld de, wNameBuffer
    call CopyToStringBuffer                       ; call CopyToStringBuffer
    mov al, [ebp + wFossilItem]                   ; ld a, [wFossilItem]
    mov [ebp + wNamedObjectIndex], al             ; ld [wNamedObjectIndex], a
    call GetItemName                              ; call GetItemName
    ret

; ---------------------------------------------------------------------------
; Port-only presentation (mart class, prize pattern): mirror the fossil list
; from the 40-wide canvas into GB_TILEMAP0 and publish it as a window
; descriptor (the compositor reads the window source, not wTileMap).
; Source rows 0..h-1 where h = bh+2 (TextBoxBorder draws top + bh middles +
; bottom); dest is FOSSIL_SROW. All registers preserved.
; ---------------------------------------------------------------------------
fossil_list_mirror:
    pushad
    mov al, [ebp + wFilteredBagItemsCount]        ; row count = 3+2*(count-1)
    dec al
    mov bx, 2
    mov esi, 3
    call AddNTimes
    lea ecx, [esi + 1]              ; drawn rows = bh+2 (top + middles + bottom)
    xor ebx, ebx
.row:
    cmp ebx, ecx
    jae .done
    mov esi, ebx
    imul esi, esi, SCREEN_TILES_W
    lea esi, [ebp + esi + wTileMap]
    mov edi, ebx
    shl edi, 5
    lea edi, [ebp + edi + GB_TILEMAP0 + FOSSIL_SROW * 32]
    push ecx
    mov ecx, FOSSIL_LIST_W
    rep movsb
    pop ecx
    inc ebx
    jmp .row
.done:
    popad
    ret

fossil_show_list_window:
    pushad
    mov ecx, [g_window_count]
    xor ebx, ebx
.check:
    cmp ebx, ecx
    jge .notfound
    imul eax, ebx, WIN_DESC_SIZE
    mov edx, [g_windows + eax + WIN_START_ROW]
    cmp edx, FOSSIL_SROW
    je .found
    inc ebx
    jmp .check
.found:
    call fossil_list_mirror
    popad
    ret
.notfound:
    popad
    call fossil_list_mirror
    mov eax, FOSSIL_MENU_WX
    mov ebx, FOSSIL_MENU_WY
    mov ecx, FOSSIL_MENU_CLIP
    mov edx, FOSSIL_MENU_MAXY
    mov esi, GB_TILEMAP0
    mov edi, FOSSIL_SROW
    call add_window
    ret

; ---------------------------------------------------------------------------
; fossil_drop_windows — port-only presentation: remove exactly the fossil
; list window descriptor, compacting the list. Template: prize_drop_windows
; (prize_menu.asm) — same scan by WIN_START_ROW, shift-down removal. Called
; at both GiveFossilToCinnabarLab exits (teardown-after-choice spec);
; CloseTextDisplay's hide_window remains the final backstop.
; All registers preserved.
; ---------------------------------------------------------------------------
fossil_drop_windows:
    pushad
    mov ecx, [g_window_count]
    test ecx, ecx
    jz .done
    xor ebx, ebx
.scan:
    cmp ebx, ecx
    jge .done
    imul eax, ebx, WIN_DESC_SIZE
    mov edx, [g_windows + eax + WIN_START_ROW]
    cmp edx, FOSSIL_SROW
    je .found
    inc ebx
    jmp .scan
.found:
    mov edi, ebx
    imul edi, edi, WIN_DESC_SIZE
    add edi, g_windows
.shift_loop:
    inc ebx
    cmp ebx, ecx
    jge .shifted
    mov esi, ebx
    imul esi, esi, WIN_DESC_SIZE
    add esi, g_windows
    push ecx
    mov ecx, WIN_DESC_SIZE / 4
    rep movsd
    pop ecx
    jmp .shift_loop
.shifted:
    dec dword [g_window_count]
.done:
    popad
    ret
