; ===========================================================================
; cinnabar_lab.asm — faithful port of pret engine/events/cinnabar_lab.asm
; (Pokemon Yellow)
;
; Implements GiveFossilToCinnabarLab (the fossil-choice menu that lets the
; player hand over a Dome/Helix Fossil), its helper PrintFossilsInBag (prints
; each fossil in the bag on its own line of that menu), and
; LoadFossilItemAndMonName (loads the resulting mon name + item name into
; wNameBuffer/wStringBuffer for the "Oh! That is a KABUTO fossil!" text).
;
; Register map (SM83 -> x86): A=AL, HL=ESI, BC=BX (B=BH, C=BL), DE=EDX (D=DH, E=DL);
; EBP = GB base. GB memory is [ebp + addr].
;
; UI PROJECTION (docs/ui_projection.md):
;   overworld-ui (fossil list box): GB(0,0) 15x(dynamic) --(anchor=top-LEFT, X+0, Y+0)--> wx=7 wy=0 clip=120 max_y=8*(4+2*(N-1))
;   (N = wFilteredBagItemsCount; the box grows by 2 rows per extra fossil, same
;   as pret's own AddNTimes-computed height)
;
; Build: nasm -f coff -I include/ -I . -o cinnabar_lab.o src/engine/events/cinnabar_lab.asm
; ===========================================================================

